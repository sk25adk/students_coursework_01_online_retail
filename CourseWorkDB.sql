-- Supplied unmarked base schema; Oracle Database 19c or later.
CREATE TABLE RT01_PriceCard (
ProductCode VARCHAR2(20) PRIMARY KEY, Price NUMBER(8,2) NOT NULL CHECK(Price>=0), Clearance NUMBER(1) NOT NULL CHECK(Clearance IN(0,1))
);

CREATE TABLE RT02_Bin (
BinID NUMBER PRIMARY KEY, SKU VARCHAR2(20) NOT NULL, OnHand NUMBER NOT NULL CHECK(OnHand>=0), ReorderAt NUMBER NOT NULL CHECK(ReorderAt>=0)
);

CREATE TABLE RT03_Line (
LineID NUMBER PRIMARY KEY, InvoiceNo NUMBER NOT NULL, Units NUMBER NOT NULL CHECK(Units>0), ChargedPrice NUMBER(8,2) NOT NULL CHECK(ChargedPrice>=0), DiscountPct NUMBER(5,2) NOT NULL CHECK(DiscountPct BETWEEN 0 AND 100)
);

CREATE TABLE RT04_Dispatch (
DispatchID NUMBER PRIMARY KEY, PromisedOn DATE NOT NULL, DeliveredOn DATE
);

CREATE TABLE RT05_CostCard (
SKU VARCHAR2(20) PRIMARY KEY, Cost NUMBER(8,2) NOT NULL CHECK(Cost>=0), SalePrice NUMBER(8,2) NOT NULL CHECK(SalePrice>=0)
);

CREATE TABLE RT06_Tender (
ReceiptID NUMBER PRIMARY KEY, TillCode VARCHAR2(10) NOT NULL, Amount NUMBER(8,2) NOT NULL CHECK(Amount>0), Method VARCHAR2(4) NOT NULL CHECK(Method IN('CASH','CARD'))
);

CREATE TABLE RT07_Slab (
FromWeight NUMBER PRIMARY KEY, ToWeight NUMBER NOT NULL, Charge NUMBER(8,2) NOT NULL CHECK(Charge>=0), CHECK(ToWeight>FromWeight)
);

CREATE TABLE RT08_Quote (
QuoteID NUMBER PRIMARY KEY, BaseAmount NUMBER(8,2) NOT NULL, ValidUntil DATE NOT NULL, OfferedPercent NUMBER(5,2)
);

CREATE TABLE RT09_ReceiptLine (
LineNo NUMBER PRIMARY KEY, SKU VARCHAR2(20) NOT NULL, Units NUMBER NOT NULL CHECK(Units>0), UnitCost NUMBER(8,2) NOT NULL CHECK(UnitCost>=0), SoldPrice NUMBER(8,2) NOT NULL CHECK(SoldPrice>=0)
);

CREATE TABLE RT10_Bid (
SKU VARCHAR2(20), VendorCode VARCHAR2(20), UnitCost NUMBER(8,2) NOT NULL, FreightEach NUMBER(8,2) NOT NULL, PRIMARY KEY(SKU,VendorCode)
);

CREATE TABLE RT11_Cell (
SKU VARCHAR2(20), DepotID NUMBER, Units NUMBER NOT NULL CHECK(Units>=0 AND Units=TRUNC(Units)), PRIMARY KEY(SKU,DepotID)
);

CREATE TABLE RT12_PromoWallet (
PromoCode VARCHAR2(20) PRIMARY KEY, Budget NUMBER(10,2) NOT NULL, Spent NUMBER(10,2) DEFAULT 0 NOT NULL
);

CREATE TABLE RT13_Receivable (
BillID NUMBER PRIMARY KEY, AmountDue NUMBER(10,2) NOT NULL CHECK(AmountDue>0), SettledOn DATE
);

CREATE TABLE RT13_Settlement (
BillID NUMBER PRIMARY KEY REFERENCES RT13_Receivable(BillID), Amount NUMBER(10,2) NOT NULL CHECK(Amount>0)
);

CREATE TABLE RT14_Buyer (
BuyerID NUMBER PRIMARY KEY, BuyerLabel VARCHAR2(80) NOT NULL, Enabled NUMBER(1) NOT NULL CHECK(Enabled IN(0,1))
);

CREATE TABLE RT14_Lot (
SKU VARCHAR2(20) PRIMARY KEY, Available NUMBER NOT NULL CHECK(Available>=0 AND Available=TRUNC(Available)), TicketPrice NUMBER(8,2) NOT NULL CHECK(TicketPrice>=0)
);

CREATE TABLE RT14_Reservation (
ReservationID NUMBER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY, BuyerID NUMBER NOT NULL REFERENCES RT14_Buyer(BuyerID), SKU VARCHAR2(20) NOT NULL REFERENCES RT14_Lot(SKU), Units NUMBER NOT NULL CHECK(Units>0), CapturedPrice NUMBER(8,2) NOT NULL
);

CREATE TABLE RT15_SalesJournal (
EntryID NUMBER PRIMARY KEY, SoldAt DATE NOT NULL, Amount NUMBER(10,2) NOT NULL CHECK(Amount>0), Refunded NUMBER(1) NOT NULL CHECK(Refunded IN(0,1))
);
